@dataclass
class AssociationRule:
    antecedents: List[str]
    consequents: List[str]
    confidence: float
    lift: float
    support: float

@dataclass
class ConceptNode:
    sctid: str                  # O ID original (pode ser 123 ou 123+456)
    fsn: str                    # Termo amigável
    is_custom: bool = False     # Flag para saber se é composto
    custom_id: str = ""         # Ex: CUST_001
    constituents: List[dict] = field(default_factory=list) # Lista das partes (basedOn)
    definition: str = ""        # Definição gerada ou buscada
    semantic_tag: str = "finding"

    def to_output_format(self):
        """Retorna o dicionário formatado conforme solicitado pelo usuário."""
        if self.is_custom:
            # Formato CUSTOM (Rico)
            formatted_based_on = [
                f"{c['id']} | {c['term']} |" for c in self.constituents
            ]
            return {
                "customSctid": self.custom_id,
                "fsn": self.fsn,
                "basedOn": formatted_based_on,
                "definition": self.definition
            }
        else:
            # Formato PADRÃO (Simples)
            return {
                "sctid": self.sctid,
                "term": self.fsn,
                "type": self.semantic_tag
            }

@dataclass
class SemanticRule:
    raw_rule: AssociationRule
    normalized_consequents: List[ConceptNode]
    validation_status: str
    validation_reason: str
    
    def to_json(self):
        # Monta a string legível da regra original
        input_str = f"{', '.join(self.raw_rule.antecedents)} -> {', '.join(self.raw_rule.consequents)}"
        
        # Gera o grounding usando o método customizado de cada nó
        grounding_list = [node.to_output_format() for node in self.normalized_consequents]

        return {
            "evidence": {
                "input": input_str,
                "metrics": {
                    "lift": round(self.raw_rule.lift, 4), 
                    "conf": round(self.raw_rule.confidence, 4),
                    "supp": round(self.raw_rule.support, 4)
                }
            },
            "grounding": grounding_list,
            "status": self.validation_status,
            "note": self.validation_reason
        }

