# 3. LOADER INTELIGENTE (COM LÓGICA DE CUSTOMIZAÇÃO)
# ==============================================================================

class SnomedMapLoader:
    def __init__(self, user_map: Dict[str, str], atom_meta: Dict[str, dict]):
        self.user_map = user_map
        self.atom_meta = atom_meta
        self._custom_counter = 1
        self._cache = {}

    def _get_next_custom_id(self):
        cid = f"CUST_{self._custom_counter:03d}"
        self._custom_counter += 1
        return cid

    def _clean_term(self, raw_text: str) -> str:
        # Remove coisas como "MovementAcceleration [g]=" e deixa só "acc_baixa"
        if "=" in raw_text:
            return raw_text.split("=", 1)[1].strip()
        return raw_text.strip()

    def _resolve_atom_name(self, sctid: str) -> str:
        if sctid in self.atom_meta:
            return self.atom_meta[sctid]['term']
        return "Unknown Concept"

    def find_concept(self, raw_text: str) -> Optional[ConceptNode]:
        core_term = self._clean_term(raw_text)
        
        # 1. Busca no Mapa
        sctid_expr = self.user_map.get(core_term)
        
        # Fallback: Procura se a chave está contida na string
        if not sctid_expr:
            for k, v in self.user_map.items():
                if k in raw_text:
                    sctid_expr = v
                    core_term = k # Normaliza o nome para o termo mapeado
                    break
        
        if not sctid_expr:
            return None

        # Check Cache
        if sctid_expr in self._cache:
            return self._cache[sctid_expr]

        # 2. Analisa se é Composto (Custom) ou Simples
        if "+" in sctid_expr:
            # === LOGICA CUSTOM ===
            parts = sctid_expr.split("+")
            constituents = []
            def_parts = []
            
            for part_id in parts:
                meta = self.atom_meta.get(part_id, {"term": "Unknown", "def": ""})
                constituents.append({"id": part_id, "term": meta['term']})
                if meta['def']:
                    def_parts.append(meta['def'])
            
            # Gera definição composta
            full_def = f"{core_term}; Combinação de: {'; '.join(def_parts)}."
            
            node = ConceptNode(
                sctid=sctid_expr,
                fsn=core_term, # Ex: acc_baixa
                is_custom=True,
                custom_id=self._get_next_custom_id(),
                constituents=constituents,
                definition=full_def,
                semantic_tag="observable entity"
            )
        else:
            # === LOGICA SIMPLES ===
            meta = self.atom_meta.get(sctid_expr, {})
            term_display = meta.get('term', core_term)
            tag = "disorder" if "Fibrillation" in term_display else "finding"
            
            node = ConceptNode(
                sctid=sctid_expr,
                fsn=term_display,
                is_custom=False,
                semantic_tag=tag
            )

        self._cache[sctid_expr] = node
        return node

