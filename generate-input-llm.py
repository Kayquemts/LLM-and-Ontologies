# 4. PROCESSADOR E EXECUTOR
# ==============================================================================

class SemanticProcessor:
    def __init__(self, ontology: SnomedMapLoader):
        self.ontology = ontology

    def process_rule(self, rule: AssociationRule) -> SemanticRule:
        grounded_concepts = []
        missing = 0
        
        for cons in rule.consequents:
            concept = self.ontology.find_concept(cons)
            if concept:
                grounded_concepts.append(concept)
            else:
                missing += 1
        
        status = "VALID"
        note_parts = []
        if missing > 0:
            status = "WARNING"
            note_parts.append(f"Failed to ground {missing} terms.")
        
        if not note_parts:
            note_parts.append(f"Successfully grounded {len(grounded_concepts)} concept(s).")

        return SemanticRule(rule, grounded_concepts, status, " ".join(note_parts))

def generate_llm_payload(rules: List[SemanticRule]):
    # Cabeçalho fixo solicitado
    header = {
        "role": "system",
        "instruction": """
          Contexto: Analise de regras de associação de sensores IoT de saude.
          Objetivo: Explicar clinicamente os padroes encontrados.
          Ontologia: Os códigos 'sctid' referem-se ao SNOMED CT. Expressoes com '+' indicam pos-coordenacao (composicao).

          Instruções:
                 1. Analise o campo 'evidence' (metricas estatisticas).
                 2. Correlacione com o 'grounding' (significado clinico).
                 3. Identifique padrões de risco (ex: Fibrilacao Atrial associada a certas atividades).
        """
    }
    
    data_list = [r.to_json() for r in rules]
    
    return {**header, "data": data_list}

def frozenset_to_list(s):
    # Utilitário para limpar o formato do pandas frozenset
    if pd.isna(s): return []
    return re.findall(r"'(.*?)'", str(s))

